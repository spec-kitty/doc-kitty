/**
 * A producer's output scan (#330): classify every file under the directory a
 * generator writes into as OWNED by that producer or AUTHORED. The Gherkin
 * generator uses it for its section (`scanOutputDir`); the pack pages of #338
 * use it per pack directory. The registry (`producers.mjs`) says which producers
 * exist; this module reads files, so it is kept out of the fs-free registry.
 *
 * @module producer-output
 */

import { existsSync, lstatSync, readdirSync, readFileSync } from 'node:fs';
import path from 'node:path';
import matter from 'gray-matter';
import { isRegenerableStamp } from './generator-stamp.mjs';

/** @param {string} a @param {string} b */
const compareCodeUnit = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

/**
 * Does a Markdown file's frontmatter stamp it as generated by `producerId`? Its
 * versioned stamp, or its retired unversioned stamp, so that regenerating
 * replaces a legacy page (#210). A file whose frontmatter does not parse is NOT
 * owned, so it is never deleted.
 *
 * @param {string} contents
 * @param {string} producerId an ownership producer of the registry
 * @returns {boolean}
 */
export function isProducerOwnedPage(contents, producerId) {
  try {
    const { data } = matter(contents);
    return isRegenerableStamp(data?.generated?.by, producerId);
  } catch {
    return false;
  }
}

/**
 * Walk `outDir` and classify every file: OWNED (a `.md` the producer stamped)
 * or AUTHORED (anything else). ANY symlink, to a file or a directory, stamped
 * target or not, is AUTHORED and never followed: a writer would otherwise write
 * or prune through it, outside `outDir`. A symlinked `outDir` is reported as the
 * authored entry `.`. Dotfiles are ignored. Returns POSIX paths relative to
 * `outDir`, code-unit sorted.
 *
 * @param {string} outDir
 * @param {string} producerId
 * @returns {{ owned: string[], authored: string[] }}
 */
export function scanProducerOutput(outDir, producerId) {
  /** @type {string[]} */
  const owned = [];
  /** @type {string[]} */
  const authored = [];
  if (!existsSync(outDir)) return { owned, authored };
  if (lstatSync(outDir).isSymbolicLink()) return { owned, authored: ['.'] };
  /** @param {string} dir */
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (entry.name.startsWith('.')) continue;
      const abs = path.join(dir, entry.name);
      const rel = path.relative(outDir, abs).split(path.sep).join('/');
      if (entry.isSymbolicLink()) {
        authored.push(rel);
        continue;
      }
      if (entry.isDirectory()) {
        walk(abs);
        continue;
      }
      if (entry.name.endsWith('.md') && isProducerOwnedPage(readFileSync(abs, 'utf8'), producerId)) owned.push(rel);
      else authored.push(rel);
    }
  };
  walk(outDir);
  return { owned: owned.sort(compareCodeUnit), authored: authored.sort(compareCodeUnit) };
}

