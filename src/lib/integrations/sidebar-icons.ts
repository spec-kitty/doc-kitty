/**
 * The sidebar-icons integration (page-chrome WP07): checks every authored icon, serves
 * the used ones through `virtual:doc-kitty/sidebar-icons`, and says whether the site
 * has any.
 *
 * WHEN it reads the sources is the point. The sources are read in `astro:config:done`,
 * after every integration's `astro:config:setup`, so a page a generator writes there is
 * seen. The answer goes in the config's one {@link BuildState}, and the two things that
 * follow it, the manifest's custom body and shaping's markers, read it when Vite loads
 * their modules, which is later still. So they cannot disagree, on a first build or a
 * second, whatever the factory saw on disk.
 */
import type { AstroIntegration } from 'astro';
import type { BuildState } from '../build-state.js';
import { collectAuthoredIcons, sidebarIconData, type SidebarIconData } from '../sidebar-icons.js';
import type { RouteShapingOptions } from './route-shaping.js';

/** The virtual module the route middleware reads the used icons from. */
export const SIDEBAR_ICONS_MODULE_ID = 'virtual:doc-kitty/sidebar-icons';

/** Generate the source of {@link SIDEBAR_ICONS_MODULE_ID}. */
export function sidebarIconsSource(data: SidebarIconData): string {
  return (
    '// AUTO-GENERATED by @spec-kitty/doc-toolkit sidebar-icons integration. Do not edit.\n' +
    `export const sidebarIcons = ${JSON.stringify(data, null, 2)};\n`
  );
}

export function sidebarIconsIntegration(
  { docsDir, indexBasename, shapeSidebar }: Pick<RouteShapingOptions, 'docsDir' | 'indexBasename' | 'shapeSidebar'>,
  state: BuildState,
): AstroIntegration {
  const RESOLVED = `\0${SIDEBAR_ICONS_MODULE_ID}`;
  let data: SidebarIconData = { links: [], groups: [] };
  const plugin = {
    name: 'doc-kitty:sidebar-icons',
    resolveId(id: string): string | null {
      return id === SIDEBAR_ICONS_MODULE_ID ? RESOLVED : null;
    },
    load(id: string): string | null {
      return id === RESOLVED ? sidebarIconsSource(data) : null;
    },
  };
  return {
    name: 'doc-kitty:sidebar-icons',
    hooks: {
      'astro:config:setup': ({ updateConfig }) => {
        updateConfig({ vite: { plugins: [plugin] } });
      },
      'astro:config:done': () => {
        const authored = sidebarIconData(collectAuthoredIcons(docsDir, { indexBasename }), new Set(state.unpublishedPaths));
        const used = authored.links.length + authored.groups.length;
        if (shapeSidebar) {
          data = authored;
          state.iconsAuthored = used > 0;
        } else if (used > 0) {
          // C-004: a sidebar the consumer wrote is never changed. Names were still checked above.
          console.warn(`[dk-sidebar-icons] ${used} authored icon(s) have no effect: this site writes its own sidebar, and icons apply to the generated one.`);
        }
      },
    },
  };
}
