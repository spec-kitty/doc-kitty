// ===========================================================================
// Sidebar and table-of-contents shaping seam (FR-011, FR-019..FR-023, C-004).
//
// Starlight 0.32 labels autogenerated subgroups with the directory name and
// sorts them by slug. The toolkit's route-data middleware (`route-middleware.ts`)
// relabels and reorders them from each directory's index page, and drops a
// near-empty table of contents. The middleware runs inside Astro's bundled
// render module, so it cannot read the docs tree itself: this integration reads
// it and serves the result as a virtual module, the transport `manifest.ts`
// already uses for slot components.
// ===========================================================================

/**
 * The virtual module the route middleware imports its build data from.
 *
 * @internal An internal seam the toolkit's own tests use; not supported API.
 */
export const ROUTE_SHAPING_MODULE_ID = 'virtual:doc-kitty/route-shaping';

/**
 * The toolkit's route middleware, as a package-export specifier so a consuming
 * site resolves it from its `@spec-kitty/doc-toolkit` dependency (the same
 * reason the carriers are specifiers).
 *
 * @internal An internal seam the toolkit's own tests use; not supported API.
 */
export const ROUTE_MIDDLEWARE = '@spec-kitty/doc-toolkit/route-middleware';

/**
 * Options for {@link routeShapingIntegration}.
 *
 * @internal An internal seam the toolkit's own tests use; not supported API.
 */
export interface RouteShapingOptions {
  /** The docs tree, relative to the site root (same value as `DocKittyOptions.docsDir`). */
  docsDir: string;
  /** The site `base`; stripped from sidebar hrefs before they are matched to directories. */
  base: string;
  /** Section-index basename(s); decides which files are directory index pages. */
  indexBasename?: IndexBasenameOption;
  /** False when the consumer supplied their own `sidebar`: it is then left exactly as written (C-004). */
  shapeSidebar: boolean;
  /** False when the site switched Starlight's prev/next links off. */
  pagination: boolean;
  /** The `sidebar.indexLabel` option (#161); absent = the locale's UI string. */
  indexLabel?: string;
}

/** The slug of the folder holding a docs-relative path (`''` for the docs root). */
const folderSlug = (rel: string): string => (rel.includes('/') ? rel.slice(0, rel.lastIndexOf('/')) : '');

/**
 * Read the slice of every docs page that sidebar shaping needs: slug, title,
 * the Starlight `sidebar` front-matter block, and whether the file is a
 * directory index. The file list is the shared walk ({@link walkMarkdownPaths}:
 * no `log.md`, dot-folders or `_meta`), read build-free for frontmatter. Slug and
 * `isIndex` come from the shared route rule (`resolveIndexEntries`, `routeOfSlug`):
 * a page is its folder's index when its route is the folder's route, so a
 * collision never reaches here (it fails the build first).
 */
function directoryMetaInputs(
  docsDir: string,
  indexBasename?: IndexBasenameOption,
  unpublishedPaths: ReadonlySet<string> = new Set(),
): DirectoryMetaInput[] {
  const root = path.resolve(process.cwd(), docsDir);
  const pages = walkMarkdownPaths(root).map((rel) => ({
    rel,
    data: matter(readFileSync(path.join(root, rel), 'utf8')).data as {
      title?: unknown;
      sidebar?: { label?: unknown; order?: unknown };
    },
  }));

  const { ids } = resolveIndexEntries(
    pages.map((page) => page.rel),
    { indexBasename },
  );
  // Slugs are resolved over every file, so a withheld file still takes part in
  // the index collision rule; it is only left out of the metadata afterwards.
  const inputs: DirectoryMetaInput[] = pages
    .filter(({ rel }) => !unpublishedPaths.has(rel))
    .map(({ rel, data }) => {
      const pageSlug = ids.get(rel) as string;
      // An index page serves its containing folder's route (`x/index` is served at
      // `/x/`), so the group is keyed by the folder; any other page keeps its own id.
      const isIndex = routeOfSlug(pageSlug) === routeOfSlug(folderSlug(rel));
      const slug = isIndex ? folderSlug(rel) : pageSlug;
      const label = data.sidebar?.label;
      const order = data.sidebar?.order;
      return {
        slug,
        title: typeof data.title === 'string' ? data.title : '',
        isIndex,
        sidebar: {
          ...(typeof label === 'string' ? { label } : {}),
          ...(typeof order === 'number' ? { order } : {}),
        },
      };
    });
  return inputs;
}

/**
 * Generate the source of `virtual:doc-kitty/route-shaping`. Plain JSON data, so
 * the middleware needs no filesystem access; the map is serialised as sorted
 * entries, so two builds of one tree emit the same module (NFR-006). Exported so
 * the consumer-precedence switch is testable without a build. The withheld
 * drafts come from the {@link BuildState} the draft-publication integration fills.
 *
 * @internal An internal seam the toolkit's own tests use; not supported API.
 */
export function routeShapingSource(
  options: RouteShapingOptions,
  state: BuildState = createBuildState(),
): string {
  const unpublished = [...new Set(state.unpublishedDirs)].sort(compareCodeUnit);
  const hidden = new Set(unpublished);
  const meta = options.shapeSidebar
    ? buildDirectoryMeta(
        directoryMetaInputs(
          options.docsDir,
          options.indexBasename,
          new Set(state.unpublishedPaths),
        ).filter(
          (input) => !hidden.has(input.slug),
        ),
      )
    : new Map();
  const data = {
    base: normalizeBasePrefix(options.base),
    shapeSidebar: options.shapeSidebar,
    pagination: options.pagination,
    directoryMeta: [...meta.entries()],
    unpublishedDirs: unpublished,
    ...(options.indexLabel ? { indexLabel: options.indexLabel } : {}),
  };
  return (
    '// AUTO-GENERATED by @spec-kitty/doc-toolkit route-shaping integration. Do not edit.\n' +
    `export const routeShaping = ${JSON.stringify(data, null, 2)};\n`
  );
}

/**
 * Serve the route-shaping data and report shaping warnings once per build.
 *
 * The module source is generated when Vite LOADS it, not when this factory
 * runs: the glossary integration writes its pages in `astro:config:setup`, and
 * their index pages must be on disk before the tree is read.
 *
 * Warnings are raised by the middleware on every page that renders the sidebar,
 * so they are collected in the process-wide sink of `build-state.ts` (cleared at
 * the start of each build's setup, so a second config starts empty) and printed here, sorted, when the
 * build is done — one line per untitled group, not one per page (FR-023).
 *
 * @internal An internal seam the toolkit's own tests use; not supported API.
 */
export function routeShapingIntegration(
  options: RouteShapingOptions,
  state: BuildState = createBuildState(),
): AstroIntegration {
  const RESOLVED = `\0${ROUTE_SHAPING_MODULE_ID}`;
  const plugin = {
    name: 'doc-kitty:route-shaping',
    resolveId(id: string): string | null {
      return id === ROUTE_SHAPING_MODULE_ID ? RESOLVED : null;
    },
    load(id: string): string | null {
      return id === RESOLVED ? routeShapingSource(options, state) : null;
    },
  };
  return {
    name: 'doc-kitty:route-shaping',
    hooks: {
      'astro:config:setup': ({ updateConfig }) => {
        shapingWarningSink().clear();
        updateConfig({ vite: { plugins: [plugin] } });
      },
      'astro:build:done': () => {
        const sink = shapingWarningSink();
        for (const warning of [...sink].sort(compareCodeUnit)) {
          console.warn(`[dk-sidebar] ${warning}`);
        }
        sink.clear();
      },
    },
  };
}

/**
 * Build the `@astrojs/sitemap` `filter`. It receives each candidate page's full
 * absolute URL and returns TRUE to keep the page. A page is kept iff BOTH gates
 * pass (INV-1 publication AND the section-level `feeds`):
 *
 *   1. **Draft gate.** Drop a page iff its route (the pathname with the site
 *      `base` stripped) EQUALS a draft route exactly. The match is ANCHORED — a
 *      plain `endsWith` would over-exclude a published page whose slug tail
 *      coincides with a draft's (e.g. `/architecture/overview/` vs a draft
 *      `/overview/`).
 *   2. **`feeds` gate.** Drop a page whose section does not feed `sitemap`.
 *      Resolved from `<docsDir>/_meta/sections.yaml`; a section that OMITS
 *      `feeds` feeds ALL FOUR surfaces (absent = all, {@link feedsSurface}), and
 *      an ABSENT registry means no feeds filtering at all — byte-compatible with
 *      the pre-feeds sitemap (a registry that declares no `feeds` drops nothing).
 *
 * The draft routes are read LAZILY, on the filter's first call (sitemap runs it
 * in `astro:build:done`), NOT when the integrations array is built: the opt-in
 * `doc-kitty:gherkin` integration (ADR-0046) writes `kind: Specification` pages
 * in `astro:config:setup`, which runs AFTER `defineDocKittyIntegrations`
 * returns. An eager read would gate the sitemap on the PRE-generation tree, so a
 * feature that had just gained `@wip` would leak its draft URL into the sitemap
 * (and one that just lost it would be wrongly dropped) for that build, while the
 * collection-backed surfaces (llms.txt, RSS, agent API) saw the fresh status.
 *
 * Exported so the composed draft+feeds gate is unit-testable without spinning up
 * the whole Astro integrations array.
 */
export function sitemapDraftFilter(
  docsDir: string,
  base: string,
  indexBasename?: IndexBasenameOption,
): (page: string) => boolean {
  let routes: Set<string> | undefined;
  const basePrefix = normalizeBasePrefix(base);
  // Load the registry from the SAME docs root the sidebar synthesis uses. Absent
  // registry → `feeds` undefined → `feedsSurface` is always true (no filtering).
  const registry = resolveSectionRegistry(path.resolve(process.cwd(), docsDir));
  const feeds = registry ? sectionFeeds(registry) : undefined;
  return (page: string): boolean => {
    let pathname: string;
    try {
      pathname = new URL(page).pathname;
    } catch {
      pathname = page;
    }
    let normalized = pathname.endsWith('/') ? pathname : `${pathname}/`;
    // Strip the site base prefix so what remains is the base-free doc route.
    if (basePrefix && normalized.startsWith(`${basePrefix}/`)) {
      normalized = normalized.slice(basePrefix.length) || '/';
    }
    // Anchored equality: the route must BE a draft route, not merely end with one.
    // Read once, at the first call (after every config:setup generator has run).
    routes ??= siteDraftRoutes(docsDir, indexBasename);
    if (routes.has(normalized)) return false;
    // `feeds` gate: derive the section from the base-free route (first path
    // segment; the root '/' → section '') and drop it if it does not feed sitemap.
    const slug = normalized.replace(/^\//, '').replace(/\/$/, '');
    if (!feedsSurface(feeds, sectionOf(slug), 'sitemap')) return false;
    return true;
  };
}
