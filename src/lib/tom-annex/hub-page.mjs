// @ts-check
/**
 * The evidence index's opt-in hub page (#401, WP07, FR-010): a Markdown Hub
 * rendered from a built, stamped index. Measures are grouped by nature in a
 * fixed order, then by scope, each with its evidence links; then the uncovered
 * measures. A caution block carries the label, the notice and the ⚖ items.
 *
 * The page is stamped by `doc-kitty-tom-annex` (ADR-0083, ADR-0087): `by`,
 * `at` and `source_digest` are the index's own, and `content_hash` is the
 * page's, by the ADR-0087 D2 Markdown rule ({@link pageContentHash}). `updated`
 * is the index's `at`. Nothing here reads the clock, so the same index always
 * renders the same bytes.
 *
 * @module tom-annex/hub-page
 */

import { createHash } from 'node:crypto';
import { MEASURE_NATURES } from '../measures-core.mjs';
import { TOM_ANNEX_COUNSEL, TOM_ANNEX_LABEL, TOM_ANNEX_NOTICE } from './core.mjs';

const TITLE = 'Evidence index (TOM)';
const DESCRIPTION = `${TOM_ANNEX_LABEL} The published pages that evidence each technical and organisational measure.`;

/** @type {Record<string, string>} */
const NATURE_HEADING = {
  technical: 'Technical measures',
  organisational: 'Organisational measures',
  legal: 'Legal measures',
  physical: 'Physical measures',
};

/** @type {Array<['system' | 'organisation', string]>} */
const SCOPES = [
  ['system', 'System'],
  ['organisation', 'Organisation'],
];

/**
 * ADR-0087 D2, `content_hash` for a Markdown page: remove the frontmatter's
 * `generated:` line and every following line that begins with a space, then
 * hash the rest (UTF-8, LF) and keep the first 12 hex digits.
 *
 * @param {string} text the page as written
 * @returns {string} `sha256:<12 hex>`
 */
export function pageContentHash(text) {
  const lines = text.replace(/\r\n/g, '\n').split('\n');
  /** @type {string[]} */
  const out = [];
  let fences = 0;
  let inStamp = false;
  for (const line of lines) {
    if (line === '---' && fences < 2) {
      fences++;
      inStamp = false;
      out.push(line);
      continue;
    }
    const inFrontmatter = fences === 1;
    if (inFrontmatter && line === 'generated:') {
      inStamp = true;
      continue;
    }
    if (inStamp && line.startsWith(' ')) continue;
    inStamp = false;
    out.push(line);
  }
  return `sha256:${createHash('sha256').update(out.join('\n'), 'utf8').digest('hex').slice(0, 12)}`;
}

/**
 * Inline Markdown text: whitespace collapsed, Markdown syntax escaped.
 *
 * @param {unknown} value
 * @returns {string}
 */
function inline(value) {
  return String(value ?? '')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/[\\`*_[\]<>|]/g, (c) => `\\${c}`);
}

/** @param {string} url @returns {string} a link destination with spaces and parentheses encoded */
const destination = (url) => url.replace(/[ ()]/g, (c) => encodeURIComponent(c));

/**
 * @param {import('./core.mjs').MeasureEntry} entry
 * @returns {string[]}
 */
function measureLines(entry) {
  const frameworks = entry.frameworks.map((f) => `${inline(f.framework)} ${inline(f.ref)}`).join('; ');
  const lines = [`- **${inline(entry.label)}** (\`${entry.id}\`)${frameworks ? `. ${frameworks}` : ''}`];
  for (const ref of entry.evidence) {
    const note = ref.note ? `: ${inline(ref.note)}` : '';
    lines.push(`  - [${inline(ref.title)}](${destination(ref.url)})${note}`);
  }
  return lines;
}

/**
 * The hub page for a stamped evidence index.
 *
 * @param {any} annex a parsed, stamped evidence index (format 1.x)
 * @returns {string}
 */
export function renderHubPage(annex) {
  const generated = annex?.generated;
  if (!generated || typeof generated.at !== 'string') {
    throw new Error(
      '[dk-tom-annex] the hub page needs a date: no evidence page carries an `updated` or `verified` date, so the index has no `generated.at`',
    );
  }
  /** @type {string[]} */
  const body = [
    `# ${TITLE}`,
    '',
    '> [!CAUTION]',
    `> **${inline(TOM_ANNEX_LABEL)}** ${inline(TOM_ANNEX_NOTICE)}`,
    '>',
    '> Open questions for data-protection counsel:',
    '>',
    ...TOM_ANNEX_COUNSEL.map((item) => `> - ${inline(item)}`),
    '',
    'This page is generated by `dockitty-tom-annex` from the built evidence index, `api/tom-annex.json`. Do not edit it by hand: change the classified pages or the measures catalog, then regenerate it.',
  ];
  for (const nature of MEASURE_NATURES) {
    /** @type {string[]} */
    const section = [];
    for (const [scope, heading] of SCOPES) {
      const entries = (annex.scopes[scope] ?? []).filter((/** @type {any} */ e) => e.nature === nature);
      if (entries.length === 0) continue;
      section.push('', `### ${heading}`, '', ...entries.flatMap(measureLines));
    }
    if (section.length > 0) body.push('', `## ${NATURE_HEADING[nature]}`, ...section);
  }
  body.push('', '## Uncovered measures', '');
  if (annex.uncovered.length === 0) {
    body.push('Every measure of the catalog has at least one evidence page.');
  } else {
    body.push('No published page evidences these measures yet.', '');
    for (const u of annex.uncovered) body.push(`- **${inline(u.label)}** (\`${u.id}\`), ${u.nature}`);
  }

  const frontmatter = (/** @type {string} */ contentHash) => [
    '---',
    'okf_version: "0.2"',
    `title: ${JSON.stringify(TITLE)}`,
    `description: ${JSON.stringify(DESCRIPTION)}`,
    'doc_status: active',
    `updated: ${generated.at}`,
    'type: Reference',
    'kind: Hub',
    'generated:',
    `  by: ${JSON.stringify(generated.by)}`,
    `  at: ${JSON.stringify(generated.at)}`,
    `  source_digest: ${JSON.stringify(generated.source_digest)}`,
    `  content_hash: ${JSON.stringify(contentHash)}`,
    '---',
    '',
  ];
  const page = (/** @type {string} */ contentHash) => `${[...frontmatter(contentHash), ...body].join('\n')}\n`;
  // The hash ignores the stamp block, so any placeholder gives the same value.
  return page(pageContentHash(page('')));
}
